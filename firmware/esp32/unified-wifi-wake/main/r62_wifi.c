static const char *TAG="R62_WIFI";
static SemaphoreHandle_t lock;
static r62_wifi_state_t state;
static bool do_scan,do_connect,do_forget,do_save,do_reconnect,do_restore;
// One previously validated AP, kept only in RAM while a manual trial runs.
// Never put attempted credentials in NVS before DHCP GOT_IP.
static wifi_config_t rollback_station;
static bool rollback_valid;
static bool pending_manual_connected;
static bool created,netif_created,driver_initialized,handlers_ready;
static bool pending_manual_save;
// DHCP-validated trial config kept only in RAM, never printed or saved early.
static wifi_config_t pending_station;
static bool pending_station_valid;
static volatile bool discard_pending_station;
static volatile bool forget_in_progress;
static unsigned reconnect_attempts;
static char pending_ssid[33],pending_password[65];

// R272: verified by NVS metadata that the Wi-Fi driver did not create its
// station namespace after two successful application revision commits.
// Save the DHCP-verified config in our own NVS; at boot use official WiFi APIs.
// Never log, transmit or persist a candidate before DHCP confirmation.
static bool saved_marker(void){
    nvs_handle_t n;
    if(nvs_open("dfwifi",NVS_READONLY,&n)!=ESP_OK)return false;
    uint8_t ok=0;bool saved=nvs_get_u8(n,"saved",&ok)==ESP_OK && ok==1;
    nvs_close(n);return saved;
}
static bool load_saved_station(wifi_config_t *out){
    if(!out)return false;
    memset(out,0,sizeof(*out));
    nvs_handle_t n;
    if(nvs_open("dfwifi",NVS_READONLY,&n)!=ESP_OK)return false;
    uint8_t saved=0;size_t len=sizeof(*out);
    esp_err_t rc=nvs_get_u8(n,"saved",&saved);
    if(rc==ESP_OK && saved==1)rc=nvs_get_blob(n,"station_v1",out,&len);
    nvs_close(n);
    if(rc!=ESP_OK || saved!=1 || len!=sizeof(*out) || !out->sta.ssid[0]){
        memset(out,0,sizeof(*out));return false;
    }
    return true;
}
static uint32_t saved_generation(void){
    nvs_handle_t n;
    if(nvs_open("dfwifi",NVS_READONLY,&n)!=ESP_OK)return 0;
    uint32_t gen=0;
    (void)nvs_get_u32(n,"revision",&gen);
    nvs_close(n);
    return gen;
}
static bool set_saved_marker(bool keep,const wifi_config_t *verified){
    if(keep && (!verified || !verified->sta.ssid[0]))return false;
    nvs_handle_t n;
    if(nvs_open("dfwifi",NVS_READWRITE,&n)!=ESP_OK)return false;
    uint32_t revision=0;
    esp_err_t e=ESP_OK;
    if(keep){
        e=nvs_get_u32(n,"revision",&revision);
        if(e==ESP_ERR_NVS_NOT_FOUND)e=ESP_OK;
        // Single NVS transaction: validated config, saved marker, revision.
        if(e==ESP_OK)e=nvs_set_blob(n,"station_v1",verified,sizeof(*verified));
        if(e==ESP_OK)e=nvs_set_u8(n,"saved",1);
        if(e==ESP_OK)e=nvs_set_u32(n,"revision",revision+1u?revision+1u:1u);
    }else{
        e=nvs_erase_key(n,"station_v1");
        if(e==ESP_ERR_NVS_NOT_FOUND)e=ESP_OK;
        if(e==ESP_OK)e=nvs_erase_key(n,"saved");
        if(e==ESP_ERR_NVS_NOT_FOUND)e=ESP_OK;
    }
    if(e==ESP_OK)e=nvs_commit(n);
    nvs_close(n);
    if(e!=ESP_OK)return false;
    if(!keep)return true;
    wifi_config_t check={0};
    bool matched=load_saved_station(&check) &&
        memcmp(check.sta.ssid,verified->sta.ssid,sizeof(check.sta.ssid))==0 &&
        memcmp(check.sta.password,verified->sta.password,sizeof(check.sta.password))==0;
    memset(&check,0,sizeof(check));
    return matched;
}


static void wifi_event(void *arg,esp_event_base_t base,int32_t id,void *data){
    if(!lock)return;
    if(xSemaphoreTake(lock,pdMS_TO_TICKS(50))!=pdTRUE)return;
    if(base==WIFI_EVENT && id==WIFI_EVENT_STA_DISCONNECTED){
        state.connected=false;state.has_ip=false;state.connecting=false;
        if(state.error==0)state.error=4;
        // An explicit esp_wifi_disconnect() is generated by switching from
        // the old AP. That is NOT a failed trial of the new credentials.
        wifi_event_sta_disconnected_t *lost=(wifi_event_sta_disconnected_t*)data;
        bool intentional=lost && lost->reason==WIFI_REASON_ASSOC_LEAVE;
        if(pending_manual_save && !intentional && !forget_in_progress){
            pending_manual_save=false;pending_manual_connected=false;
            discard_pending_station=true;
            if(rollback_valid){do_restore=true;do_reconnect=false;}
            state.error=5;
        }else if(state.saved && !pending_manual_save && !do_restore &&
                 !forget_in_progress && !intentional &&
                 reconnect_attempts<5)do_reconnect=true;
    }
    if(base==WIFI_EVENT && id==WIFI_EVENT_STA_CONNECTED){
        state.connected=true;state.connecting=false;state.error=0;
        // Match actual B-AP's connected SSID, not a delayed STA_CONNECTED
        // receipt from A during the intentional switch. IP from A must never
        // trigger a premature B-password NVS save.
        wifi_event_sta_connected_t *joined=(wifi_event_sta_connected_t*)data;
        if(pending_manual_save && joined && joined->ssid_len>0 &&
           joined->ssid_len<=32 &&
           strnlen(state.current,sizeof(state.current))==joined->ssid_len &&
           memcmp(joined->ssid,state.current,joined->ssid_len)==0)
            pending_manual_connected=true;
    }
    if(base==IP_EVENT && id==IP_EVENT_STA_GOT_IP){
        // Drop an old A network's delayed DHCP receipt while B is staged.
        // Never advertise an IP or persist B until B's CONNECTED SSID matches.
        if(pending_manual_save && !pending_manual_connected){
            xSemaphoreGive(lock);return;
        }
        ip_event_got_ip_t *evt=(ip_event_got_ip_t*)data;
        snprintf(state.ip,sizeof(state.ip),IPSTR,IP2STR(&evt->ip_info.ip));
        state.ready=true;state.connected=true;state.has_ip=true;state.connecting=false;state.error=0;
        state.needs_setup=false;
        reconnect_attempts=0;do_reconnect=false;
        if(pending_manual_save && pending_manual_connected){
            state.persistence_stage=2;
            do_save=true;
        }
    }
    xSemaphoreGive(lock);
}
/* R100 read-only truth: preserve the first raw failing ESP-IDF stage.
 * Never log SSID, password, device identity or audio.
 * Only invoked from the Wi-Fi worker, never from a lock-owned callback.
 */
static bool wifi_error(uint8_t step,esp_err_t error){
    const size_t dma=heap_caps_get_largest_free_block(MALLOC_CAP_DMA|MALLOC_CAP_INTERNAL);
    const size_t biggest=heap_caps_get_largest_free_block(MALLOC_CAP_8BIT|MALLOC_CAP_INTERNAL);
    if(lock && xSemaphoreTake(lock,pdMS_TO_TICKS(70))==pdTRUE){
        state.diagnostic_stage=step;
        state.diagnostic_esp_error=(int)error;
        state.diagnostic_dma_largest=(uint32_t)dma;
        state.diagnostic_internal_largest=(uint32_t)biggest;
        xSemaphoreGive(lock);
    }
    ESP_LOGW(TAG,"R100_WIFI_START_FAIL stage=%u esp_error=%d dma_largest=%lu internal_largest=%lu",
             (unsigned)step,(int)error,(unsigned long)dma,(unsigned long)biggest);
    return false;
}
static void wifi_step(uint8_t step){
    /* Read-only per-stage minimum contiguous heap observations (no SSIDs). */
    const uint32_t dma=(uint32_t)heap_caps_get_largest_free_block(MALLOC_CAP_DMA|MALLOC_CAP_INTERNAL);
    const uint32_t internal=(uint32_t)heap_caps_get_free_size(MALLOC_CAP_INTERNAL|MALLOC_CAP_8BIT);
    if(lock && xSemaphoreTake(lock,pdMS_TO_TICKS(70))==pdTRUE){
        state.diagnostic_stage=step;
        state.diagnostic_esp_error=0;
        if(state.diagnostic_dma_min==0 || dma<state.diagnostic_dma_min){
            state.diagnostic_dma_min=dma;
            state.diagnostic_min_stage=step;
        }
        if(state.diagnostic_internal_min==0 || internal<state.diagnostic_internal_min)
            state.diagnostic_internal_min=internal;
        xSemaphoreGive(lock);
    }
}
static bool start_wifi(void){
    if(created)return true;
    size_t internal_free=heap_caps_get_free_size(MALLOC_CAP_INTERNAL);
    size_t internal_largest=heap_caps_get_largest_free_block(MALLOC_CAP_INTERNAL);
    ESP_LOGI(TAG,"R62_WIFI_HEAP internal_free=%lu internal_largest=%lu",
      (unsigned long)internal_free,(unsigned long)internal_largest);
    // The actual ESP32 must retain contiguous internal heap for USB,
    // microphone, I2S and LVGL. Calibrate threshold with physical receipts.
    // Fail closed instead of asking Wi-Fi to exhaust the working voice path.
    // R268 isolated *diagnostic* probe only: R266 failed before IDF init
    // at 91,635 free / 38,912 largest. Attempt the real driver once with
    // a bounded reservation, then still fail closed on an actual low reserve.
    // No production promotion without WN9/PCM2/SD/Wi-Fi concurrency gates.
    if(internal_free<80*1024 || internal_largest<32*1024){
      ESP_LOGW(TAG,"R268_WIFI_DIAG_PRECHECK_TOO_LOW");
      return wifi_error(1,ESP_ERR_NO_MEM);
    }
    wifi_step(2);
    esp_err_t e=esp_netif_init();
    if(e!=ESP_OK && e!=ESP_ERR_INVALID_STATE){
      return wifi_error(2,e);
    }
    wifi_step(3);
    e=esp_event_loop_create_default();
    if(e!=ESP_OK && e!=ESP_ERR_INVALID_STATE){
      return wifi_error(3,e);
    }
    if(!netif_created){
        wifi_step(4);
        if(!esp_netif_create_default_wifi_sta()){
            return wifi_error(4,ESP_ERR_NO_MEM);
        }
        netif_created=true;
    }
    if(!driver_initialized){
        wifi_init_config_t cfg=WIFI_INIT_CONFIG_DEFAULT();
        wifi_step(5);
        e=esp_wifi_init(&cfg);
        if(e!=ESP_OK)return wifi_error(5,e);
        driver_initialized=true;
    }
    // R272 uses the explicit committed app NVS snapshot, not the missing
    // WiFi-driver FLASH namespace. Manual trials stay RAM-only.
    wifi_step(6);
    e=esp_wifi_set_storage(WIFI_STORAGE_RAM);
    if(e!=ESP_OK)return wifi_error(6,e);
    if(!handlers_ready){
        esp_event_handler_instance_t h1,h2,h3;
        wifi_step(7);
        e=esp_event_handler_instance_register(
            WIFI_EVENT,WIFI_EVENT_STA_CONNECTED,wifi_event,NULL,&h1);
        if(e!=ESP_OK)return wifi_error(7,e);
        wifi_step(8);
        e=esp_event_handler_instance_register(
            WIFI_EVENT,WIFI_EVENT_STA_DISCONNECTED,wifi_event,NULL,&h2);
        if(e!=ESP_OK){
            esp_event_handler_instance_unregister(WIFI_EVENT,WIFI_EVENT_STA_CONNECTED,h1);
            return wifi_error(8,e);
        }
        wifi_step(9);
        e=esp_event_handler_instance_register(
            IP_EVENT,IP_EVENT_STA_GOT_IP,wifi_event,NULL,&h3);
        if(e!=ESP_OK){
            esp_event_handler_instance_unregister(WIFI_EVENT,WIFI_EVENT_STA_CONNECTED,h1);
            esp_event_handler_instance_unregister(WIFI_EVENT,WIFI_EVENT_STA_DISCONNECTED,h2);
            return wifi_error(9,e);
        }
        handlers_ready=true;
    }
    wifi_step(10);
    e=esp_wifi_set_mode(WIFI_MODE_STA);
    if(e!=ESP_OK)return wifi_error(10,e);
    // Restore committed station through official Wi-Fi API, with no logs.
    wifi_config_t boot_station={0};
    bool boot_has_ssid=state.saved && load_saved_station(&boot_station);
    if(boot_has_ssid){
        esp_err_t apply=esp_wifi_set_config(WIFI_IF_STA,&boot_station);
        if(apply!=ESP_OK){
            memset(&boot_station,0,sizeof(boot_station));
            return wifi_error(19,apply);
        }
        wifi_config_t readback={0};
        boot_has_ssid=esp_wifi_get_config(WIFI_IF_STA,&readback)==ESP_OK &&
            readback.sta.ssid[0] &&
            memcmp(readback.sta.ssid,boot_station.sta.ssid,
                   sizeof(boot_station.sta.ssid))==0;
        memset(&readback,0,sizeof(readback));
    }
    memset(&boot_station,0,sizeof(boot_station));
    if(lock && xSemaphoreTake(lock,pdMS_TO_TICKS(70))==pdTRUE){
        state.station_config_loaded=boot_has_ssid;
        xSemaphoreGive(lock);
    }
    wifi_step(11);
    e=esp_wifi_start();
    if(e!=ESP_OK)return wifi_error(11,e);
    // R90 post-start safety: keep enough contiguous internal heap for
    // USB microphone, PCM2 audio and LVGL. Wi-Fi stays off on failure.
    size_t residual=heap_caps_get_free_size(MALLOC_CAP_INTERNAL|MALLOC_CAP_8BIT);
    size_t largest=heap_caps_get_largest_free_block(MALLOC_CAP_INTERNAL|MALLOC_CAP_8BIT);
    ESP_LOGI(TAG,"R90_WIFI_POSTINIT internal_free=%lu largest=%lu",
             (unsigned long)residual,(unsigned long)largest);
    /* R198 actually displayed LCD ESP_ERR_NO_MEM when postinit free=98,891
       and largest=31,744. Demand a stronger reserve before retaining Wi-Fi.
       Never loosen voice/LCD safety to make a scan appear successful. */
    if(residual<72*1024 || largest<32*1024){
        ESP_LOGW(TAG,"R268_WIFI_DIAG_POSTINIT_RESERVE_FAILED");
        (void)wifi_error(12,ESP_ERR_NO_MEM);
        (void)esp_wifi_stop();
        (void)esp_wifi_deinit();
        driver_initialized=false;created=false;
        return false;
    }
    created=true;wifi_step(13);
    // On reboot the saved station reconnects without an explicit SCAN.
    // Mark the *driver* ready here, then GOT_IP separately proves DHCP.
    if(lock && xSemaphoreTake(lock,pdMS_TO_TICKS(70))==pdTRUE){
        state.ready=true;
        xSemaphoreGive(lock);
    }
    return true;
}
static void wifi_task(void *arg){
    (void)arg;
    for(;;){
        bool scan=false,connect=false,forget=false,save=false,reconnect=false,restore=false;
        char ssid[33]={0},password[65]={0};
        if(xSemaphoreTake(lock,portMAX_DELAY)==pdTRUE){
            scan=do_scan;connect=do_connect;forget=do_forget;
            save=do_save;reconnect=do_reconnect;restore=do_restore;
            do_scan=false;do_connect=false;do_forget=false;
            do_save=false;do_reconnect=false;do_restore=false;
            if(discard_pending_station && !save){
                memset(&pending_station,0,sizeof(pending_station));
                pending_station_valid=false;
                discard_pending_station=false;
            }
            if(connect){
                memcpy(ssid,pending_ssid,sizeof(ssid));
                memcpy(password,pending_password,sizeof(password));
                memset(pending_password,0,sizeof(pending_password));
            }
            xSemaphoreGive(lock);
        }
        if(scan||connect||save||forget||reconnect||restore){
            if(!start_wifi()){
                if(xSemaphoreTake(lock,portMAX_DELAY)==pdTRUE){
                    state.error=1;state.scanning=false;state.connecting=false;
                    // A saved AP remains eligible after transient boot-time
                    // heap shortage. Do not discard the only reconnection.
                    if(state.saved && !forget && !connect &&
                       reconnect_attempts<5)do_reconnect=true;
                    xSemaphoreGive(lock);
                }
                if(reconnect)reconnect_attempts++;
                memset(password,0,sizeof(password));
                vTaskDelay(pdMS_TO_TICKS(3000));continue;
            }
            if(forget){
                forget_in_progress=true;
                do_restore=false;rollback_valid=false;
                memset(&rollback_station,0,sizeof(rollback_station));
                memset(&pending_station,0,sizeof(pending_station));
                pending_station_valid=false;discard_pending_station=false;
                // Explicit UI action only. Never erase the default NVS or
                // unrelated animation rules, and never print the password.
                esp_wifi_disconnect();
                wifi_config_t empty={0};
                esp_err_t rc=esp_wifi_set_storage(WIFI_STORAGE_RAM);
                if(rc==ESP_OK)rc=esp_wifi_set_config(WIFI_IF_STA,&empty);
                if(rc==ESP_OK && set_saved_marker(false,NULL)){
                    if(xSemaphoreTake(lock,pdMS_TO_TICKS(70))==pdTRUE){
                        state.saved=false;state.has_ip=false;state.connected=false;
                        state.needs_setup=false;state.persistence_stage=0;
                        state.current[0]=0;state.ip[0]=0;state.error=0;
                        pending_manual_save=false;reconnect_attempts=5;
                        xSemaphoreGive(lock);
                    }
                }else wifi_error(15,rc==ESP_OK?ESP_FAIL:rc);
                forget_in_progress=false;
            }
            if(save){
                // Critical: never persist the driver's unverified get_config().
                // It may return an empty SSID after a RAM-only trial even
                // though a DHCP event has fired. Keep the accepted candidate
                // from the physical password entry until AFTER DHCP.
                bool candidate_ok=pending_station_valid &&
                    pending_manual_connected && state.has_ip &&
                    pending_station.sta.ssid[0]!=0 &&
                    strncmp((const char*)pending_station.sta.ssid,
                            state.current,sizeof(pending_station.sta.ssid))==0;
                esp_err_t rc=candidate_ok?ESP_OK:ESP_ERR_INVALID_STATE;
                if(rc==ESP_OK)rc=esp_wifi_set_storage(WIFI_STORAGE_RAM);
                if(rc==ESP_OK)rc=esp_wifi_set_config(WIFI_IF_STA,&pending_station);
                wifi_config_t verified={0};
                if(rc==ESP_OK)rc=esp_wifi_get_config(WIFI_IF_STA,&verified);
                bool confirmed=rc==ESP_OK &&
                    memcmp(verified.sta.ssid,pending_station.sta.ssid,
                           sizeof(verified.sta.ssid))==0 &&
                    memcmp(verified.sta.password,pending_station.sta.password,
                           sizeof(verified.sta.password))==0 &&
                    verified.sta.ssid[0]!=0;
                memset(&verified,0,sizeof(verified));
                // Driver readback is only a live-config check. Cold boot must
                // separately prove NVS persistence; never claim it here.
                bool stored=confirmed && set_saved_marker(true,&pending_station);
                uint32_t current_generation=stored?saved_generation():0;
                memset(&pending_station,0,sizeof(pending_station));
                pending_station_valid=false;discard_pending_station=false;
                if(xSemaphoreTake(lock,pdMS_TO_TICKS(70))==pdTRUE){
                    state.saved=stored;state.persistence_stage=stored?3:4;
                    if(stored)state.persistence_generation=current_generation;
                    pending_manual_save=false;
                    pending_manual_connected=false;
                    if(!stored)state.error=6;
                    xSemaphoreGive(lock);
                }
                if(stored){
                    rollback_valid=false;do_restore=false;
                    memset(&rollback_station,0,sizeof(rollback_station));
                }else wifi_error(16,rc==ESP_OK?ESP_FAIL:rc);
                ESP_LOGI(TAG,"R211_WIFI_PERSIST_AFTER_IP ok=%u",(unsigned)stored);
            }
            // Authenticate B failed: restore previously saved A in RAM only.
            // No NVS writes, never call connect from the event callback.
            if(restore && !connect && !forget && !save && rollback_valid){
                wifi_config_t trusted=rollback_station;
                rollback_valid=false;
                memset(&rollback_station,0,sizeof(rollback_station));
                memset(&pending_station,0,sizeof(pending_station));
                pending_station_valid=false;discard_pending_station=false;
                esp_err_t rc=esp_wifi_set_storage(WIFI_STORAGE_RAM);
                if(rc==ESP_OK)rc=esp_wifi_set_config(WIFI_IF_STA,&trusted);
                memset(&trusted,0,sizeof(trusted));
                if(rc==ESP_OK)rc=esp_wifi_connect();
                if(xSemaphoreTake(lock,pdMS_TO_TICKS(70))==pdTRUE){
                    pending_manual_save=false;pending_manual_connected=false;
                    state.connecting=rc==ESP_OK;state.has_ip=false;
                    state.error=rc==ESP_OK?0:5;
                    xSemaphoreGive(lock);
                }
                if(rc!=ESP_OK)wifi_error(18,rc);
                ESP_LOGI(TAG,"R222_SAVED_AP_RESTORE accepted=%u",(unsigned)(rc==ESP_OK));
            }
            if(reconnect && !scan && !connect && !forget && !restore){
                if(reconnect_attempts++<5){
                    vTaskDelay(pdMS_TO_TICKS(3000));
                    if(!do_connect && !do_forget){
                        esp_err_t rc=esp_wifi_connect();
                        if(rc==ESP_ERR_WIFI_SSID){
                            // The old app marker is present, but ESP-IDF did
                            // not load a usable SSID. Stop useless retries.
                            // NVS and any password remain UNTOUCHED; only a
                            // physical user scan/join may replace them.
                            (void)wifi_error(17,rc);
                            if(xSemaphoreTake(lock,pdMS_TO_TICKS(70))==pdTRUE){
                                state.needs_setup=true;
                                state.persistence_stage=0;
                                state.saved=false; // session-only correction
                                state.error=7;
                                state.connecting=false;
                                xSemaphoreGive(lock);
                            }
                            reconnect_attempts=5;
                            ESP_LOGW(TAG,"R268_SAVED_WIFI_HAS_NO_VALID_SSID_REPAIR_ON_SCREEN");
                        }else if(rc!=ESP_OK)wifi_error(17,rc);
                    }
                }
            }
            if(connect){
                // Capture A from the live driver before replacing it with B.
                // Preserve the trusted snapshot across repeated manual trials
                // until a DHCP-confirmed success, explicit forget or restore.
                if(state.saved && !rollback_valid){
                    wifi_config_t prior={0};
                    if(esp_wifi_get_config(WIFI_IF_STA,&prior)==ESP_OK &&
                       prior.sta.ssid[0]){
                        rollback_station=prior;rollback_valid=true;
                    }
                    memset(&prior,0,sizeof(prior));
                }
                wifi_config_t cfg={0};
                /* R250 -O2: preserve the original bounded NUL-terminated
                 * copy semantics without strncpy truncation diagnostics. */
                size_t ssid_len=strnlen(ssid,sizeof(cfg.sta.ssid)-1);
                size_t password_len=strnlen(password,sizeof(cfg.sta.password)-1);
                memcpy(cfg.sta.ssid,ssid,ssid_len);
                memcpy(cfg.sta.password,password,password_len);
                memset(password,0,sizeof(password));
                pending_manual_save=true; // block stale-network reconnect
                pending_manual_connected=false;
                esp_wifi_disconnect();
                esp_err_t rc=esp_wifi_set_storage(WIFI_STORAGE_RAM);
                if(rc==ESP_OK)rc=esp_wifi_set_config(WIFI_IF_STA,&cfg);
                if(rc==ESP_OK){
                    pending_station=cfg;pending_station_valid=true;
                }else{
                    memset(&pending_station,0,sizeof(pending_station));
                    pending_station_valid=false;
                }
                memset(&cfg,0,sizeof(cfg));
                if(rc==ESP_OK)rc=esp_wifi_connect();
                pending_manual_save=rc==ESP_OK;
                discard_pending_station=false;
                if(rc!=ESP_OK){
                    memset(&pending_station,0,sizeof(pending_station));
                    pending_station_valid=false;
                    if(rollback_valid)do_restore=true;
                }
                if(xSemaphoreTake(lock,portMAX_DELAY)==pdTRUE){
                    state.connecting=rc==ESP_OK;
                    state.error=rc==ESP_OK?0:5;
                    xSemaphoreGive(lock);
                }
                ESP_LOGI(TAG,"R62_JOIN_ATTEMPT accepted=%u",(unsigned)(rc==ESP_OK));
            }
            if(scan){
                wifi_scan_config_t config={.show_hidden=false};
                esp_err_t rc=esp_wifi_scan_start(&config,true);
                uint16_t found=0;
                wifi_ap_record_t records[8]={0};
                if(rc==ESP_OK){
                    if(esp_wifi_scan_get_ap_num(&found)==ESP_OK){
                        uint16_t take=found>8?8:found;
                        if(esp_wifi_scan_get_ap_records(&take,records)==ESP_OK){
                            if(xSemaphoreTake(lock,portMAX_DELAY)==pdTRUE){
                                state.count=take;
                                for(int i=0;i<take;i++){
                                    memcpy(state.ssid[i],records[i].ssid,32);
                                    state.ssid[i][32]=0;
                                    state.signal[i]=records[i].rssi;
                                }
                                xSemaphoreGive(lock);
                            }
                        }else rc=ESP_FAIL;
                    }else rc=ESP_FAIL;
                }
                if(rc!=ESP_OK)(void)wifi_error(14,rc);
                // Manual scanning must not strand previously saved Wi-Fi.
                // Reconnect *after* the blocking scan completes, never from
                // the event callback, never while switching/forgetting.
                if(xSemaphoreTake(lock,portMAX_DELAY)==pdTRUE){
                    if(state.saved && !state.has_ip && !pending_manual_save &&
                       !forget_in_progress && reconnect_attempts<5)
                        do_reconnect=true;
                    xSemaphoreGive(lock);
                }
                if(xSemaphoreTake(lock,portMAX_DELAY)==pdTRUE){
                    state.scanning=false;state.ready=rc==ESP_OK;
                    state.error=rc==ESP_OK?0:2;
                    xSemaphoreGive(lock);
                }
                // Never reveal user-visible nearby SSIDs to serial logs.
                ESP_LOGI(TAG,"R62_SCAN_DONE ok=%u count=%u",
                    (unsigned)(rc==ESP_OK),(unsigned)(rc==ESP_OK?found:0));
            }
        }
        vTaskDelay(pdMS_TO_TICKS(100));
    }
}
void r62_wifi_begin(void){
    if(lock)return;
    lock=xSemaphoreCreateMutex();
    if(!lock)return;
    // Old rev=2 marker has no credential blob. Stop empty-SSID retry.
    wifi_config_t persisted={0};
    state.saved=saved_marker() && load_saved_station(&persisted);
    memset(&persisted,0,sizeof(persisted));
    state.persistence_generation=saved_generation();
    state.persistence_stage=state.saved?3:0;
    if(!state.saved && state.persistence_generation){
        state.needs_setup=true;state.error=7;
        state.diagnostic_stage=17;state.diagnostic_esp_error=ESP_ERR_WIFI_SSID;
    }
    if(xTaskCreate(wifi_task,"wifi_sta",6144,NULL,3,NULL)!=pdPASS){
        vSemaphoreDelete(lock);lock=NULL;return;
    }
    // A saved network triggers a single low-priority boot attempt, after the
    // SD/LVGL/USB tasks are created. No network if the user never joined.
    // A legacy saved marker without a station blob requires on-device setup.
    // Start the driver immediately after WN9 is ready (as R270 did), before
    // late UI/audio allocations fragment the internal DMA heap. Do NOT scan
    // or persist a guessed credential. The empty-SSID connect is rejected.
    if(state.saved || (state.needs_setup && state.persistence_generation>0)){
        do_reconnect=true;
    }
}
bool r62_wifi_scan(void){
    if(!lock)r62_wifi_begin();
    if(!lock)return false;
    if(xSemaphoreTake(lock,pdMS_TO_TICKS(25))!=pdTRUE)return false;
    if(state.scanning||state.connecting||do_scan||do_connect){
        xSemaphoreGive(lock);return false;
    }
    state.scanning=true;state.ready=false;state.count=0;do_scan=true;
    state.error=0;state.diagnostic_stage=0;state.diagnostic_esp_error=0;
    xSemaphoreGive(lock);return true;
}
bool r62_wifi_connect(const char *ssid,const char *password){
    if(!lock||!ssid||!password)return false;
    size_t n=strnlen(ssid,33),k=strnlen(password,65);
    if(!n||n>32||k>63||(k && k<8))return false;
    if(xSemaphoreTake(lock,pdMS_TO_TICKS(25))!=pdTRUE)return false;
    memcpy(pending_ssid,ssid,n+1);
    memcpy(pending_password,password,k+1);
    strncpy(state.current,ssid,sizeof(state.current)-1);
    state.connecting=true;state.connected=false;state.has_ip=false;
    state.error=0;state.needs_setup=false;state.persistence_stage=1;
    do_connect=true;
    reconnect_attempts=0;pending_manual_save=false;
    pending_manual_connected=false;do_reconnect=false;do_restore=false;
    xSemaphoreGive(lock);
    return true;
}
bool r62_wifi_forget(void){
    if(!lock)return false;
    if(xSemaphoreTake(lock,pdMS_TO_TICKS(25))!=pdTRUE)return false;
    if(do_forget || state.scanning || state.connecting || do_connect){
        xSemaphoreGive(lock);return false;
    }
    do_forget=true;do_reconnect=false;
    xSemaphoreGive(lock);return true;
}
void r62_wifi_snapshot(r62_wifi_state_t *out){
    if(!out)return;
    memset(out,0,sizeof(*out));
    if(!lock)return;
    if(xSemaphoreTake(lock,pdMS_TO_TICKS(25))==pdTRUE){
        *out=state;xSemaphoreGive(lock);
    }
}
